"""
The Word rendering of a methods draft.

The draft is the one artifact of this tool a user edits by hand rather than
reads, so the two things worth testing are that the file is a document Word
will open without offering to repair it, and that a gap is still a gap once it
has been through the renderer. Everything else is layout.
"""

import io
import xml.etree.ElementTree as ET
import zipfile

import pytest

from mep_cmap import docx_writer as D
from mep_cmap import tms_rat as T
from mep_cmap.reporting import load_tms_rat_mapping

from test_tms_rat_assessment import _rec

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def _blocks():
    results, faults = T.assess([_rec()], load_tms_rat_mapping(), study="S")
    return T.methods_blocks(results, faults, study="S", tool_version="1.4.6")


def _parts(data):
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        return {n: z.read(n).decode("utf-8") for n in z.namelist()}


# ── the package ──────────────────────────────────────────────────────────────

def test_every_part_a_word_document_needs_is_present():
    """
    A missing part does not fail loudly. Word offers to repair the file, and
    the user concludes the tool produced something broken.
    """
    parts = _parts(D.document_bytes(_blocks()))
    assert set(parts) == {"[Content_Types].xml", "_rels/.rels",
                          "word/_rels/document.xml.rels",
                          "word/styles.xml", "word/document.xml"}


def test_every_part_is_well_formed_xml():
    for name, text in _parts(D.document_bytes(_blocks())).items():
        ET.fromstring(text)          # raises if it is not


def test_styles_are_related_from_the_document():
    """
    styles.xml declared in [Content_Types] but not related from document.xml
    is a part Word never reads, so the headings silently lose their styles.
    """
    parts = _parts(D.document_bytes(_blocks()))
    assert "styles.xml" in parts["word/_rels/document.xml.rels"]
    assert "/word/styles.xml" in parts["[Content_Types].xml"]


def test_the_same_blocks_produce_the_same_bytes():
    """A document that differs run to run cannot be diffed."""
    blocks = _blocks()
    assert D.document_bytes(blocks) == D.document_bytes(blocks)


# ── the content ──────────────────────────────────────────────────────────────

def test_the_headings_use_real_word_heading_styles():
    """
    Direct formatting that looks like a heading cannot be restyled by a journal
    template, and does not appear in the navigation pane. The whole point of
    the docx over the markdown is that it goes into a manuscript.
    """
    doc = ET.fromstring(_parts(D.document_bytes(_blocks()))["word/document.xml"])
    styles = [p.find(f"{W}pPr/{W}pStyle").get(f"{W}val")
              for p in doc.iter(f"{W}p")
              if p.find(f"{W}pPr/{W}pStyle") is not None]
    assert "Heading1" in styles and "Heading2" in styles


def test_a_gap_marker_is_its_own_highlighted_run():
    """
    The marker must survive as searchable text AND be formatted. Formatting
    alone is lost on paste into a plain editor; text alone is skimmed past.
    """
    doc = ET.fromstring(_parts(D.document_bytes(_blocks()))["word/document.xml"])
    gaps = [r for r in doc.iter(f"{W}r")
            if r.find(f"{W}rPr/{W}highlight") is not None]
    assert gaps, "no highlighted run in a draft full of gaps"
    for r in gaps:
        text = r.find(f"{W}t").text
        assert text.startswith("[TMS-RAT ") and text.endswith("]")


def test_a_known_fact_is_not_highlighted():
    """Highlighting everything would be the same as highlighting nothing."""
    doc = ET.fromstring(_parts(D.document_bytes(_blocks()))["word/document.xml"])
    plain = [r.find(f"{W}t").text for r in doc.iter(f"{W}r")
             if r.find(f"{W}rPr/{W}highlight") is None]
    assert any("Magstim" in (t or "") for t in plain)


def test_the_preamble_example_is_not_flagged_as_a_gap():
    """
    The one paragraph explaining what a gap looks like must not be the first
    thing the reader is told to go and fix.
    """
    doc = ET.fromstring(_parts(D.document_bytes(_blocks()))["word/document.xml"])
    for r in doc.iter(f"{W}r"):
        text = r.find(f"{W}t").text or ""
        if "Generated by MEP-CMAP Analyser" in text:
            assert r.find(f"{W}rPr/{W}highlight") is None
            assert "[TMS-RAT ...]" in text
            break
    else:
        pytest.fail("the preamble is missing from the document")


def test_no_text_is_lost_between_the_markdown_and_the_document():
    """
    The two renderings read the same blocks, so a word in one and not the
    other means a renderer is dropping content rather than formatting it.
    """
    blocks = _blocks()
    doc = ET.fromstring(_parts(D.document_bytes(blocks))["word/document.xml"])
    from_docx = "".join(t.text or "" for t in doc.iter(f"{W}t"))
    for block in blocks:
        for run in block["runs"]:
            assert run["text"].strip() in from_docx


def test_a_control_character_does_not_produce_a_repairable_file():
    """
    An instrument string carrying a stray control byte is not representable in
    XML at all, and the failure surfaces as Word refusing the whole document.
    """
    blocks = [{"kind": "para", "level": 0,
               "runs": [{"text": "Coil\x07 model\x00 D70", "gap": False}]}]
    doc = ET.fromstring(_parts(D.document_bytes(blocks))["word/document.xml"])
    assert "".join(t.text or "" for t in doc.iter(f"{W}t")) == "Coil model D70"


def test_ampersands_and_angle_brackets_are_escaped():
    blocks = [{"kind": "para", "level": 0,
               "runs": [{"text": "Bistim & <200^2>", "gap": False}]}]
    doc = ET.fromstring(_parts(D.document_bytes(blocks))["word/document.xml"])
    assert "".join(t.text or "" for t in doc.iter(f"{W}t")) == "Bistim & <200^2>"


def test_a_leading_space_in_a_run_is_preserved():
    """Runs abut, so a dropped space runs two words together."""
    blocks = [{"kind": "para", "level": 0,
               "runs": [{"text": "Stimulator: ", "gap": False},
                        {"text": "[TMS-RAT D1: Stimulator]", "gap": True}]}]
    parts = _parts(D.document_bytes(blocks))
    assert 'xml:space="preserve"' in parts["word/document.xml"]


# ── readability by a real OOXML parser ───────────────────────────────────────

def test_python_docx_can_read_the_document(tmp_path):
    """
    Asserting on our own XML proves it matches what we meant to write, not
    that a Word implementation accepts it. python-docx is a dev-only
    dependency for exactly this: an independent parser reading the file back.
    """
    docx = pytest.importorskip("docx")
    path = tmp_path / "methods.docx"
    path.write_bytes(D.document_bytes(_blocks()))
    document = docx.Document(str(path))
    text = "\n".join(p.text for p in document.paragraphs)
    assert "Methods (draft)" in text
    assert "[TMS-RAT" in text
    assert any(p.style.name == "Heading 1" for p in document.paragraphs)
